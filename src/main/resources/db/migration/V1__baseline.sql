-- Baseline: the schema as Hibernate generated it (ddl-auto=update) before migrations were introduced.
-- IF NOT EXISTS makes this a no-op on databases created by that older setup, and the full schema on new ones.
-- Kept to portable SQL so it runs on PostgreSQL and on H2 (PostgreSQL mode) in tests.

CREATE TABLE IF NOT EXISTS users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    role       VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS wallets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL UNIQUE REFERENCES users (id),
    balance    NUMERIC(19, 4) NOT NULL,
    currency   VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS holdings (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT         NOT NULL REFERENCES wallets (id),
    currency  VARCHAR(3)     NOT NULL,
    amount    NUMERIC(19, 4) NOT NULL,
    UNIQUE (wallet_id, currency)
);

CREATE TABLE IF NOT EXISTS wallet_transactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id     BIGINT         NOT NULL REFERENCES wallets (id),
    type          VARCHAR(20)    NOT NULL,
    from_currency VARCHAR(3),
    from_amount   NUMERIC(19, 4),
    to_currency   VARCHAR(3)     NOT NULL,
    to_amount     NUMERIC(19, 4) NOT NULL,
    rate          NUMERIC(19, 8),
    created_at    TIMESTAMP(6)   NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_wallet_tx_wallet_created ON wallet_transactions (wallet_id, created_at);
