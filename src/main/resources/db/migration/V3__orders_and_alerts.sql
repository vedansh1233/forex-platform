-- Limit orders: convert `amount` of from_currency into to_currency once the rate reaches target_rate.
CREATE TABLE limit_orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id       BIGINT          NOT NULL REFERENCES wallets (id),
    from_currency   VARCHAR(10)     NOT NULL,
    to_currency     VARCHAR(10)     NOT NULL,
    amount          NUMERIC(28, 8)  NOT NULL,
    target_rate     NUMERIC(38, 18) NOT NULL,
    status          VARCHAR(20)     NOT NULL,
    created_at      TIMESTAMP(6)    NOT NULL,
    closed_at       TIMESTAMP(6),
    fill_rate       NUMERIC(38, 18),
    received_amount NUMERIC(28, 8),
    transaction_id  BIGINT REFERENCES wallet_transactions (id),
    failure_reason  VARCHAR(255)
);

CREATE INDEX idx_limit_orders_status ON limit_orders (status);
CREATE INDEX idx_limit_orders_wallet_created ON limit_orders (wallet_id, created_at);

-- Price alerts: notify the user when base/quote crosses target_rate in the given direction.
CREATE TABLE price_alerts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT          NOT NULL REFERENCES users (id),
    base_currency  VARCHAR(10)     NOT NULL,
    quote_currency VARCHAR(10)     NOT NULL,
    direction      VARCHAR(10)     NOT NULL,
    target_rate    NUMERIC(38, 18) NOT NULL,
    status         VARCHAR(20)     NOT NULL,
    seen           BOOLEAN         NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP(6)    NOT NULL,
    triggered_at   TIMESTAMP(6),
    triggered_rate NUMERIC(38, 18)
);

CREATE INDEX idx_price_alerts_status ON price_alerts (status);
CREATE INDEX idx_price_alerts_user_created ON price_alerts (user_id, created_at);
